export type FoodId = keyof typeof foods;

export function normalizeFoodName(name: string): string {
  return name.normalize("NFC").trim().replace(/\s+/gu, " ")
    .replace(/\s*\.\s*/gu, ".").toLocaleLowerCase("tr-TR");
}

const aliases = new Map<string, Set<FoodId>>();
for (const id of Object.keys(foods) as FoodId[]) {
  for (const name of foods[id]) {
    const key = normalizeFoodName(name);
    const ids = aliases.get(key) ?? new Set<FoodId>();
    ids.add(id);
    aliases.set(key, ids);
  }
}

export function identifyFood(name: string): ReadonlySet<FoodId> {
  return aliases.get(normalizeFoodName(name)) ?? new Set<FoodId>();
}
